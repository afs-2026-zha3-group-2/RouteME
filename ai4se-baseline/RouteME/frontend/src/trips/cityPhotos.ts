/**
 * 去掉行政区划后缀，让「上海市」「上海」都能命中同一张图。
 * 带「·」的显示名（港澳台）：台湾取后半段市名，港澳取前半段省级名。
 */
function cityKey(name: string): string {
  if (!name.includes('·')) {
    return name.replace(/(特别行政区|市|县)$/u, '').trim();
  }
  const [prefix, rest] = name.split('·').map((part) => part.trim());
  const base = prefix === '台湾' ? rest : prefix;
  return base.replace(/(特别行政区|市|县)$/u, '').trim();
}

export function cityPhoto(...names: Array<string | undefined>): string | null {
  for (const name of names) {
    if (name === undefined || name === '') {
      continue;
    }
    const photo = CITY_PHOTOS[cityKey(name)];
    if (photo !== undefined) {
      return photo;
    }
  }
  return null;
}
