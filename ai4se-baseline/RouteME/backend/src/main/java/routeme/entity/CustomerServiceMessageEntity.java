package routeme.entity;

import java.time.Instant;

import com.baomidou.mybatisplus.annotation.IdType;
import com.baomidou.mybatisplus.annotation.TableId;
import com.baomidou.mybatisplus.annotation.TableName;

import routeme.pojo.CustomerServiceMessage;

/** {@code customer_service_messages} row。 */
@TableName("customer_service_messages")
public class CustomerServiceMessageEntity {

    @TableId(type = IdType.INPUT)
    private Long id;

    private Long sessionId;

    private String senderType;

    private Long senderId;

    private String content;

    private String createdAt;

    public CustomerServiceMessage toMessage() {
        return new CustomerServiceMessage(
                id,
                sessionId,
                senderType,
                senderId,
                content,
                Instant.parse(createdAt));
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getSessionId() {
        return sessionId;
    }

    public void setSessionId(Long sessionId) {
        this.sessionId = sessionId;
    }

    public String getSenderType() {
        return senderType;
    }

    public void setSenderType(String senderType) {
        this.senderType = senderType;
    }

    public Long getSenderId() {
        return senderId;
    }

    public void setSenderId(Long senderId) {
        this.senderId = senderId;
    }

    public String getContent() {
        return content;
    }

    public void setContent(String content) {
        this.content = content;
    }

    public String getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(String createdAt) {
        this.createdAt = createdAt;
    }
}